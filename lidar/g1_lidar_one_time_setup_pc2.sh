  chmod +x "$LAUNCH_SCRIPT"
  log "Created $LAUNCH_SCRIPT"
}

main() {
  info "G1 LiDAR one-time setup/check for PC2"

  need_cmd ip
  need_cmd awk
  need_cmd grep

  if [[ ! -f "/opt/ros/$ROS_DISTRO_NAME/setup.bash" ]]; then
    die "ROS 2 $ROS_DISTRO_NAME not found at /opt/ros/$ROS_DISTRO_NAME/setup.bash. Install ROS Foxy first."
  fi

  sudo_apt_install_missing \
    git curl xauth x11-apps mesa-utils \
    ros-"$ROS_DISTRO_NAME"-rviz2 \
    ros-"$ROS_DISTRO_NAME"-rviz-common \
    ros-"$ROS_DISTRO_NAME"-rviz-default-plugins \
    ros-"$ROS_DISTRO_NAME"-rviz-ogre-vendor \
    ros-"$ROS_DISTRO_NAME"-tf2-ros \
    ros-"$ROS_DISTRO_NAME"-rmw-cyclonedds-cpp \
    ros-"$ROS_DISTRO_NAME"-rosidl-generator-dds-idl \
    python3-colcon-common-extensions \
    libyaml-cpp-dev

  ensure_unitree_ros2_present
  maybe_build_unitree_ws

  local iface="${G1_IFACE:-}"
  if [[ -z "$iface" ]]; then
    iface="$(detect_iface || true)"
  fi

  if [[ -z "$iface" ]]; then
    die "Could not detect robot network interface. Re-run with G1_IFACE=<interface>, e.g. G1_IFACE=eth0 $0"
  fi

  info "Using network interface: $iface"
  ip -o -4 addr show "$iface" || true

  write_env_file "$iface"
  write_launcher

  # Basic validation.
  # shellcheck disable=SC1090
  source_relaxed "$ENV_FILE"

  log "Environment check:"
  echo "  RMW_IMPLEMENTATION=${RMW_IMPLEMENTATION:-}"
  echo "  CYCLONEDDS_URI=$CYCLONEDDS_URI"
  echo "  G1_LIDAR_TOPIC=$G1_LIDAR_TOPIC"
  echo "  G1_LIDAR_FRAME=$G1_LIDAR_FRAME"

  echo
  info "Current LiDAR/cloud topics visible from this shell:"
  ros2 daemon stop >/dev/null 2>&1 || true
  ros2 daemon start >/dev/null 2>&1 || true
  sleep 2
  ros2 topic list 2>/dev/null | grep -E 'utlidar|livox|cloud|imu' || warn "No lidar/cloud topics discovered yet."

  echo
  log "Done."
  echo "Next time, after ssh -Y into PC2, run:"
  echo "  ~/bin/g1_lidar_rviz.sh"
}

main "$@"
